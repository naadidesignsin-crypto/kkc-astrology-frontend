export function toTeluguValue(value?: string | number | boolean | null): string {
  if (value === null || value === undefined || value === "") {
    return "-";
  }

  if (typeof value !== "string") {
    return String(value);
  }

  return TELUGU_VALUE_MAP[value] || translateKundaliSentence(value);
}

export function translateKundaliSentence(value?: string | null): string {
  if (!value) {
    return "-";
  }

  let translated = value;

  Object.entries(TELUGU_SENTENCE_REPLACEMENTS)
    .sort(([a], [b]) => b.length - a.length)
    .forEach(([hindi, telugu]) => {
      translated = translated.replaceAll(hindi, telugu);
    });

  Object.entries(TELUGU_VALUE_MAP)
    .sort(([a], [b]) => b.length - a.length)
    .forEach(([hindi, telugu]) => {
      translated = translated.replaceAll(hindi, telugu);
    });

  return translated;
}